def check_address(address, port):
    """Refuse an address or UDP port another service already uses."""
    routes = json.loads(run("ip", "-j", "-4", "route", "show", "table", "all").stdout or "[]")
    mine = ipaddress.ip_network(f"{address}/32")
    for route in routes:
        if route.get("dev") == WG_INTERFACE or not route.get("dst") or route["dst"] == "default":
            continue
        if ipaddress.ip_network(route["dst"], strict=False).overlaps(mine):
            raise RuntimeError(f"{address} overlaps an existing route on {route.get('dev')}")
    if unit_state(f"wg-quick@{WG_INTERFACE}")[0] != "active" and run("ss", "-Hlun", f"sport = :{port}").stdout.strip():
        raise RuntimeError(f"UDP port {port} is already in use")


def wireguard_config(address, port, phone, phone_key, mtu):
    existing = WG_CONF.read_text(encoding="utf-8") if WG_CONF.is_file() else ""
    found = re.search(r"^PrivateKey\s*=\s*(\S+)", existing, re.M)
    private = found.group(1) if found else run("wg", "genkey").stdout.strip()
    found = re.search(r"^Address\s*=\s*(\S+)", existing, re.M)
    # Keep an existing prefix (the first host used /30) so redeploying does not
    # restart the interface and drop an established tunnel.
    address_value = found.group(1) if found and found.group(1).split("/")[0] == address else f"{address}/32"
    if not phone_key:
        found = re.search(r"^PublicKey\s*=\s*(\S+)", existing, re.M)
        phone_key = found.group(1) if found else None
    if phone_key and not KEY.match(phone_key):
        raise RuntimeError("invalid phone public key")
    interface = f"[Interface]\nAddress = {address_value}\nListenPort = {port}\nPrivateKey = {private}\nMTU = {mtu}\n"
    peer = f"\n[Peer]\nPublicKey = {phone_key}\nAllowedIPs = {phone}/32\n" if phone_key else ""
    old_interface = existing.split("[Peer]")[0].strip()
    return interface + peer, old_interface != interface.strip(), private


def apply_wireguard(text, interface_changed):
    WG_CONF.parent.mkdir(mode=0o700, exist_ok=True)
    changed = write_file(WG_CONF, text, 0o600)
    unit = f"wg-quick@{WG_INTERFACE}"
    active, enabled = unit_state(unit)
    if active != "active":
        run("systemctl", "enable", "--now", unit)
        return "started"
    if enabled != "enabled":
        run("systemctl", "enable", unit)
    if interface_changed:
        run("systemctl", "restart", unit)
        return "restarted"
    action = None
    if changed:
        stripped = run("wg-quick", "strip", WG_INTERFACE).stdout
        run("wg", "syncconf", WG_INTERFACE, "/dev/stdin", input=stripped)
        action = "peers synced"
    ensure_peer_routes(text)
    return action


def ensure_peer_routes(text):
    """Route every peer's AllowedIPs into the interface.

    wg-quick adds these routes only when it brings the interface up, and
    `wg syncconf` never does. A host first deployed without the phone's key
    therefore had no route to the phone once the key arrived: replies to the
    console and the adapter's connections left through the default gateway.
    A /30 address hid this on the first host, since its connected route
    covers the phone.
    """
    for line in re.findall(r"^AllowedIPs\s*=\s*(.+)$", text, re.M):
        for network in filter(None, (part.strip() for part in line.split(","))):
            ipaddress.ip_network(network, strict=False)
            run("ip", "-6" if ":" in network else "-4", "route", "replace", network, "dev", WG_INTERFACE)


def server_public_key():
    if not WG_CONF.is_file():
        return None
    found = re.search(r"^PrivateKey\s*=\s*(\S+)", WG_CONF.read_text(encoding="utf-8"), re.M)
    return run("wg", "pubkey", input=found.group(1) + "\n").stdout.strip() if found else None


def configure_ufw(port, phone, address, web_port):
    if not shutil.which("ufw") or "Status: active" not in run("ufw", "status", check=False).stdout:
        log("ufw inactive or missing; leaving the host firewall untouched")
        return False
    # Explicit even where a broader range already covers the port, so narrowing
    # that range later cannot silently cut SimLocation off.
    run("ufw", "allow", f"{port}/udp", "comment", "SimLocation WireGuard")
    run("ufw", "allow", "in", "on", WG_INTERFACE, "from", phone, "to", address, "port", str(web_port),
        "proto", "tcp", "comment", "SimLocation console")
    return True


def configure_nft(web_uid, tunnel_uid, phone, address, web_port):
    text = NFT_TEMPLATE.format(web_uid=web_uid, tunnel_uid=tunnel_uid, phone=phone, address=address, web_port=web_port)
    with tempfile.NamedTemporaryFile("w", suffix=".nft", delete=False) as handle:
        handle.write(text)
    try:
        run("nft", "-c", "-f", handle.name)
    finally:
        os.unlink(handle.name)
    return write_file(ETC / "firewall.nft", text, 0o600)


def deploy(params):
    if os.geteuid() != 0:
        raise RuntimeError("must run as root")
    address, phone = params["address"], params["phone"]
    port, web_port = params["wg_port"], params["web_port"]
    for value in (address, phone):
        ipaddress.ip_address(value)
    report = {"packages": ensure_packages(), "restarts": [], "pending": []}
    check_address(address, port)
    python, added = ensure_python()
    report["packages"] += added
    web_owner = ensure_user("simlocation", WEB_HOME)
    tunnel_owner = ensure_user("simlocation-tunnel", TUNNEL_HOME)
    ensure_dir(ETC, 0o711)
    ensure_dir(WEB_HOME, 0o700, web_owner)
    # Hands root-owned leftovers of the old root adapter to its account.
    chown_tree(TUNNEL_HOME, tunnel_owner)
    report["venv_installed"] = ensure_venv(python, params["requirements"])
    changed_code = install_code(params["bundle"], params["revision"])
    report["code_changed"] = len(changed_code)
    # Before any unit points the adapter at a non-root account.
    self_test_tunnel()

    pair_changed = write_as(tunnel_owner, TUNNEL_HOME, PAIR_RECORD, base64.b64decode(params["pair_record"]))
    network = {"udid": params["udid"], "host": phone, "port": params["pairing_port"],
               "pair_record": str(PAIR_RECORD), "keepalive": params["keepalive"]}
    network_changed = write_file(ETC / "network.json", json.dumps(network, indent=2) + "\n", 0o640,
                                 (0, tunnel_owner[1]))

    env = read_env(ETC / "web.env")
    password_hash = env.get("SIMLOCATION_WEB_PASSWORD_HASH")
    lines = ["# Generated by deploy/fleet.py; change the inventory and redeploy instead of editing.",
             f"SIMLOCATION_MAP_LISTEN={address}", f"SIMLOCATION_MAP_PORT={web_port}",
             f"SIMLOCATION_WEB_USER={params['web_user']}", f"SIMLOCATION_WEB_LABEL={params['label']}",
             f"SIMLOCATION_TCP_KEEPALIVE={params['tcp_keepalive']}"]
    if params.get("default_location"):
        lat, lon = params["default_location"]
        lines += [f"SIMLOCATION_DEFAULT_LAT={lat}", f"SIMLOCATION_DEFAULT_LON={lon}"]
    if password_hash:
        lines.append(f"SIMLOCATION_WEB_PASSWORD_HASH={password_hash}")
    web_env_changed = write_file(ETC / "web.env", "\n".join(lines) + "\n", 0o600)
    report["password_set"] = bool(password_hash)

    devices_path = WEB_HOME / "devices.json"
    try:
        devices = json.loads(read_private(devices_path, WEB_HOME) or b"{}")
    except (OSError, ValueError, RuntimeError):
        devices = {}
    devices = devices if isinstance(devices, dict) else {}
    aliases = devices.get("aliases") if isinstance(devices.get("aliases"), dict) else {}
    aliases[params["alias"]] = params["udid"]
    devices = {"aliases": aliases, "default": devices.get("default") or params["udid"]}
    write_as(web_owner, WEB_HOME, devices_path, json.dumps(devices, ensure_ascii=False, indent=2))

    units_changed = [name for name, text in params["units"].items() if write_file(SYSTEMD / name, text, 0o644)]
    if units_changed:
        run("systemctl", "daemon-reload")
    firewall_changed = configure_nft(web_owner[0], tunnel_owner[0], phone, address, web_port)
    report["ufw"] = configure_ufw(port, phone, address, web_port)

    for unit in ("simlocation-firewall", "simlocation-network", "simlocation-web"):
        run("systemctl", "enable", unit)
    if firewall_changed or "simlocation-firewall.service" in units_changed or unit_state("simlocation-firewall")[0] != "active":
        run("systemctl", "restart", "simlocation-firewall")
        report["restarts"].append("simlocation-firewall")

    text, interface_changed, _private = wireguard_config(address, port, phone, params.get("phone_key"), params["mtu"])
    action = apply_wireguard(text, interface_changed)
    if action:
        report["restarts"].append(f"wg-quick@{WG_INTERFACE} ({action})")
    old_phone_conf = ETC / "wireguard-phone.conf"
    if params.get("phone_key") and old_phone_conf.exists():
        old_phone_conf.unlink()

    network_restart = (pair_changed or network_changed or "simlocation-network.service" in units_changed
                       or any(name.startswith("deploy/network_tunneld") for name in changed_code))
    if unit_state("simlocation-network")[0] != "active":
        run("systemctl", "restart", "simlocation-network")
        report["restarts"].append("simlocation-network (started)")
    elif network_restart:
        if tunnel_registered(params["udid"]) and not params.get("restart_network"):
            # A tunnel cannot be rebuilt while the phone is on cellular.
            report["pending"].append("simlocation-network: tunnel is up; rerun with --restart-network on Wi-Fi")
        else:
            run("systemctl", "restart", "simlocation-network")
            report["restarts"].append("simlocation-network")

    web_restart = (web_env_changed or "simlocation-web.service" in units_changed
                   or any(name.startswith(("bin/", "web/")) or name == "VERSION" for name in changed_code))
    if unit_state("simlocation-web")[0] != "active":
        run("systemctl", "restart", "simlocation-web")
        report["restarts"].append("simlocation-web (started)")
    elif web_restart:
        # KillMode=process: location sessions survive the console restart.
        run("systemctl", "restart", "simlocation-web")
        report["restarts"].append("simlocation-web")
    report["developer_image_cached"] = prefetch_developer_image()
    report["server_public_key"] = server_public_key()
    report["status"] = status(params)
    return report


def set_phone_key(params):
    if not KEY.match(params["public_key"]):
        raise RuntimeError("invalid phone public key")
    if not WG_CONF.is_file():
        raise RuntimeError("WireGuard is not configured here; deploy first")
    existing = WG_CONF.read_text(encoding="utf-8")
    address = re.search(r"^Address\s*=\s*([^/\s]+)", existing, re.M).group(1)
    port = int(re.search(r"^ListenPort\s*=\s*(\d+)", existing, re.M).group(1))
    mtu = re.search(r"^MTU\s*=\s*(\d+)", existing, re.M)
    text, interface_changed, _private = wireguard_config(address, port, params["phone"], params["public_key"],
                                                         int(mtu.group(1)) if mtu else 1280)
    action = apply_wireguard(text, interface_changed)
    old_phone_conf = ETC / "wireguard-phone.conf"
    removed = old_phone_conf.exists()
    if removed:
        old_phone_conf.unlink()
    return {"server_public_key": server_public_key(), "listen_port": port, "address": address,
            "applied": action, "removed_old_phone_conf": removed}


def set_password(params):
    password_hash = params["password_hash"]
    if not re.fullmatch(r"scrypt:\d+:\d+:\d+:[A-Za-z0-9_-]+:[A-Za-z0-9_-]+", password_hash):
        raise RuntimeError("unexpected password hash format")
    path = ETC / "web.env"
    lines = [line for line in path.read_text(encoding="utf-8").splitlines()
             if not line.startswith("SIMLOCATION_WEB_PASSWORD_HASH=")] if path.is_file() else []
    lines.append(f"SIMLOCATION_WEB_PASSWORD_HASH={password_hash}")
    write_file(path, "\n".join(lines) + "\n", 0o600)
    # Sessions live in memory and end with the restart, which a new password wants.
    run("systemctl", "restart", "simlocation-web")
    return {"restarted": True}


def favorites_get(_params):
    data = read_private(WEB_HOME / "favorites.json", WEB_HOME)
    return {"favorites": json.loads(data) if data is not None else None}


def favorites_put(params):
    data = params["favorites"]
    if not isinstance(data, dict) or not isinstance(data.get("items"), list):
        raise RuntimeError("favorites must be an object with an items list")
    owner = pwd.getpwnam("simlocation")
    write_as((owner.pw_uid, owner.pw_gid), WEB_HOME, WEB_HOME / "favorites.json",
             json.dumps(data, ensure_ascii=False, indent=2))
    return {"items": len(data["items"])}


def pair_get(_params):
    data = read_private(PAIR_RECORD, TUNNEL_HOME)
    if data is None:
        raise RuntimeError("no pairing record on this host")
    return {"record": base64.b64encode(data).decode("ascii")}


def status(_params=None):
    env = read_env(ETC / "web.env")
    address, port = env.get("SIMLOCATION_MAP_LISTEN"), env.get("SIMLOCATION_MAP_PORT")
    web = None
    if address and port:
        try:
            with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(
                    f"http://{address}:{port}/login", timeout=5) as response:
                web = response.status
        except Exception as exc:
            web = getattr(exc, "code", None) or type(exc).__name__
    udid = None
    try:
        udid = json.loads((ETC / "network.json").read_text(encoding="utf-8")).get("udid")
    except (OSError, ValueError):
        pass
    revision = (APP / "REVISION").read_text(encoding="utf-8").strip() if (APP / "REVISION").is_file() else None
    network_user = run("systemctl", "show", "-p", "User", "--value", "simlocation-network", check=False).stdout.strip()
    return {
        "hostname": socket.gethostname(), "revision": revision, "pmd3": installed_pmd3(),
        "units": {unit: unit_state(unit) for unit in UNITS}, "network_user": network_user or "root",
        "peers": wireguard_peers(), "tunnel": tunnel_registered(udid) if udid else None,
        "web": web, "password_set": bool(env.get("SIMLOCATION_WEB_PASSWORD_HASH")),
        "sessions": active_sessions(), "address": address,
        "old_phone_key_file": (ETC / "wireguard-phone.conf").exists(),
    }


def main(function, params):
    handlers = {"deploy": deploy, "set_phone_key": set_phone_key, "set_password": set_password,
                "favorites_get": favorites_get, "favorites_put": favorites_put,
                "pair_get": pair_get, "status": status}
    try:
        result = {"ok": True, "result": handlers[function](params)}
    except Exception as exc:
        result = {"ok": False, "error": f"{type(exc).__name__}: {exc}"}
    print(RESULT_MARKER + json.dumps(result, ensure_ascii=False), flush=True)
