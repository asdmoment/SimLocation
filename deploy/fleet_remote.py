def log(message):
    print(f"[{socket.gethostname()}] {message}", file=sys.stderr, flush=True)


def run(*args, check=True, input=None, timeout=600, env=None):
    result = subprocess.run(args, input=input, capture_output=True, text=True, timeout=timeout, env=env)
    if check and result.returncode:
        detail = (result.stderr or result.stdout).strip()[-800:]
        raise RuntimeError(f"`{' '.join(args[:3])}` failed ({result.returncode}): {detail}")
    return result


def digest(data):
    return hashlib.sha256(data).hexdigest() if data is not None else None


def file_digest(path):
    return digest(path.read_bytes()) if path.is_file() else None


def open_nofollow(path, flags):
    """Open path refusing a symbolic link as its last component; the parents must be root's."""
    return os.open(path, flags | os.O_NOFOLLOW | os.O_CLOEXEC)


def write_file(path, data, mode=0o644, owner=(0, 0)):
    """Atomic write into a root-owned directory. True when the content changed.

    The new file is created exclusively, gets its owner and mode through the
    descriptor and only then replaces the old one, so it is never readable by
    anyone else and no path is followed after the rename.
    """
    data = data.encode("utf-8") if isinstance(data, str) else data
    try:
        fd = open_nofollow(path, os.O_RDONLY | os.O_NONBLOCK)
    except FileNotFoundError:
        current = None
    else:
        with os.fdopen(fd, "rb") as handle:
            if not stat.S_ISREG(os.fstat(handle.fileno()).st_mode):
                raise RuntimeError(f"{path} is not a regular file")
            current = handle.read()
            if current == data:
                os.fchown(handle.fileno(), *owner)
                os.fchmod(handle.fileno(), mode)
                return False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
            os.fchown(handle.fileno(), *owner)
            os.fchmod(handle.fileno(), mode)
        os.replace(temporary, path)
    except BaseException:
        with suppress(FileNotFoundError):
            os.unlink(temporary)
        raise
    return True


def ensure_dir(path, mode, owner=(0, 0)):
    """Create or fix a directory whose parent is root's (/etc, /var/lib)."""
    path.mkdir(parents=True, exist_ok=True)
    fd = open_nofollow(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fchown(fd, *owner)
        os.fchmod(fd, mode)
    finally:
        os.close(fd)


def read_private(path, top):
    """Read a file below an account-owned directory without following any link.

    Every component below `top` is opened relative to its parent with
    O_NOFOLLOW, so a link the account planted cannot point root at another
    file. Returns None when the file does not exist.
    """
    parts = path.relative_to(top).parts
    fd = open_nofollow(top, os.O_RDONLY | os.O_DIRECTORY)
    try:
        for part in parts[:-1]:
            try:
                child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
            except FileNotFoundError:
                return None
            os.close(fd)
            fd = child
        try:
            file_fd = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=fd)
        except FileNotFoundError:
            return None
    finally:
        os.close(fd)
    with os.fdopen(file_fd, "rb") as handle:
        if not stat.S_ISREG(os.fstat(handle.fileno()).st_mode):
            raise RuntimeError(f"{path} is not a regular file")
        return handle.read()


# Runs as the owning account (see write_as): it can only touch what that
# account could already write, whatever links it has planted.
WRITE_AS_ACCOUNT = r"""
import os, sys, tempfile
path, mode = sys.argv[1], int(sys.argv[2], 8)
data = sys.stdin.buffer.read()
directory = os.path.dirname(path)
os.makedirs(directory, mode=0o700, exist_ok=True)
fd, temporary = tempfile.mkstemp(dir=directory, prefix=".fleet-")
try:
    with os.fdopen(fd, "wb") as handle:
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
        os.fchmod(handle.fileno(), mode)
    os.replace(temporary, path)
except BaseException:
    os.unlink(temporary)
    raise
"""


def write_as(owner, top, path, data, mode=0o600):
    """Write a file below an account-owned directory as that account. True when it changed."""
    data = data.encode("utf-8") if isinstance(data, str) else data
    try:
        if read_private(path, top) == data:
            return False
    except (OSError, RuntimeError):
        pass  # a link or something other than a file: the account's own rename replaces it
    result = subprocess.run(["setpriv", f"--reuid={owner[0]}", f"--regid={owner[1]}", "--clear-groups",
                             "--inh-caps=-all", sys.executable, "-I", "-c", WRITE_AS_ACCOUNT,
                             str(path), format(mode, "o")],
                            input=data, capture_output=True, timeout=60)
    if result.returncode:
        detail = result.stderr.decode("utf-8", "replace").strip()[-400:]
        raise RuntimeError(f"writing {path} as uid {owner[0]} failed: {detail}")
    return True


def chown_tree(top, owner):
    """Hand a tree to its account (migrating root-owned leftovers) without following links."""
    for _directory, dirnames, filenames, dirfd in os.fwalk(top, follow_symlinks=False):
        for name in dirnames + filenames:
            os.chown(name, *owner, dir_fd=dirfd, follow_symlinks=False)
    ensure_dir(top, 0o700, owner)


def ensure_user(name, home):
    try:
        entry = pwd.getpwnam(name)
    except KeyError:
        run("useradd", "--system", "--user-group", "--home-dir", str(home), "--no-create-home",
            "--shell", "/usr/sbin/nologin", name)
        entry = pwd.getpwnam(name)
        log(f"created system user {name}")
    return entry.pw_uid, entry.pw_gid


def unit_state(unit):
    active = run("systemctl", "is-active", unit, check=False).stdout.strip()
    enabled = run("systemctl", "is-enabled", unit, check=False).stdout.strip()
    return active, enabled


def read_env(path):
    values = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            key, separator, value = line.partition("=")
            if separator and not key.startswith("#"):
                values[key.strip()] = value.strip()
    return values


def apt_install(*packages):
    log("apt install " + " ".join(packages))
    run("apt-get", "update", "-q", env=APT_ENV, timeout=900)
    run("apt-get", "install", "-y", "-q", "--no-install-recommends", *packages, env=APT_ENV, timeout=900)


def tunnel_registered(udid):
    """True when tunneld holds a tunnel for udid; None when tunneld does not answer."""
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    try:
        with opener.open("http://127.0.0.1:49151/", timeout=3) as response:
            data = json.load(response)
    except Exception:
        return None
    return bool(isinstance(data, dict) and data.get(udid))


def active_sessions():
    sessions = []
    for path in sorted(WEB_HOME.glob("*.state.json")):
        try:
            state = json.loads(read_private(path, WEB_HOME) or b"{}")
        except (OSError, ValueError, RuntimeError):
            continue
        pid = state.get("pid")
        alive = isinstance(pid, int) and pid > 0 and Path(f"/proc/{pid}").exists()
        sessions.append({"device": path.name[:8] + "…", "status": state.get("status"),
                         "mode": state.get("mode"), "alive": alive})
    return sessions


def masked(endpoint):
    host, _, port = endpoint.rpartition(":")
    parts = host.split(".")
    return ".".join(parts[:2] + ["x", "x"]) + ":" + port if len(parts) == 4 else "(ipv6)"


def wireguard_peers():
    result = run("wg", "show", WG_INTERFACE, "dump", check=False)
    if result.returncode:
        return None
    peers = []
    now = int(time.time())
    for line in result.stdout.strip().splitlines()[1:]:
        fields = line.split("\t")
        if len(fields) < 8:
            continue
        handshake = int(fields[4])
        peers.append({"public_key": fields[0][:8] + "…",
                      "endpoint": masked(fields[2]) if fields[2] != "(none)" else None,
                      "handshake_age": now - handshake if handshake else None,
                      "rx": int(fields[5]), "tx": int(fields[6])})
    return peers


def ensure_packages():
    missing = []
    if not shutil.which("wg") or not shutil.which("wg-quick"):
        missing.append("wireguard-tools")
    if not shutil.which("nft"):
        missing.append("nftables")
    if missing:
        apt_install(*missing)
    return missing


def usable_python(path, need_venv=True):
    check = PSK_CHECK if not need_venv else "import ensurepip, venv; " + PSK_CHECK
    return bool(path) and run(path, "-c", check, check=False).returncode == 0


def ensure_python():
    """An interpreter with TLS-PSK. Ubuntu 24.04's python3 is 3.12, so add deadsnakes there."""
    for name in ("python3", "python3.14", "python3.13"):
        path = shutil.which(name)
        if usable_python(path):
            return path, []
    if not shutil.which("add-apt-repository"):
        apt_install("software-properties-common")
    log("adding ppa:deadsnakes for python3.14 (this python3 has no TLS-PSK)")
    run("add-apt-repository", "-y", "ppa:deadsnakes/ppa", env=APT_ENV, timeout=900)
    apt_install("python3.14", "python3.14-venv")
    path = shutil.which("python3.14")
    if not usable_python(path):
        raise RuntimeError("python3.14 from deadsnakes has no TLS-PSK or venv")
    return path, ["python3.14 (deadsnakes)"]


def installed_pmd3():
    python = VENV / "bin" / "python"
    if not python.exists():
        return None
    result = run(str(python), "-c", "import importlib.metadata as m, requests; print(m.version('pymobiledevice3'))",
                 check=False)
    return result.stdout.strip() if result.returncode == 0 else None


def ensure_venv(python, lock_text):
    write_file(ETC / "requirements.lock", lock_text, 0o644)
    venv_python = VENV / "bin" / "python"
    if venv_python.exists() and not usable_python(str(venv_python), need_venv=False):
        log("existing venv has no TLS-PSK; rebuilding it")
        shutil.rmtree(VENV)
    if installed_pmd3() == PINNED:
        return False
    if not venv_python.exists():
        run(python, "-m", "venv", str(VENV))
    log(f"pip install pymobiledevice3 {PINNED} from the pinned lock (a few minutes)")
    pip = (str(venv_python), "-m", "pip", "install", "--disable-pip-version-check", "--no-input",
           "--timeout", "30", "--retries", "3", "-r", str(ETC / "requirements.lock"))
    if run(*pip, check=False, timeout=1800).returncode:
        version = run(python, "-c", "import sys; print('%d.%d' % sys.version_info[:2])").stdout.strip()
        apt_install(f"python{version}-dev", "gcc")
        run(*pip, timeout=1800)
    if installed_pmd3() != PINNED:
        raise RuntimeError("pymobiledevice3 version mismatch after install")
    return True


def install_code(bundle, revision):
    """Swap in a new tree only when a file differs; keep one previous tree."""
    staging = Path(tempfile.mkdtemp(prefix="simlocation.", dir=str(APP.parent)))
    try:
        with tarfile.open(fileobj=io.BytesIO(base64.b64decode(bundle)), mode="r:gz") as archive:
            archive.extractall(staging, filter="data")
        (staging / "REVISION").write_text(revision + "\n", encoding="utf-8")
        new = {p.relative_to(staging).as_posix(): file_digest(p) for p in staging.rglob("*") if p.is_file()}
        old = {p.relative_to(APP).as_posix(): file_digest(p) for p in APP.rglob("*")
               if p.is_file() and "__pycache__" not in p.parts} if APP.is_dir() else {}
        changed = sorted(name for name in set(new) | set(old) if new.get(name) != old.get(name))
        if not changed:
            shutil.rmtree(staging)
            return []
        for path in [staging, *staging.rglob("*")]:
            os.chown(path, 0, 0)
            os.chmod(path, 0o755 if path.is_dir() else 0o644)
        if PREVIOUS.exists():
            shutil.rmtree(PREVIOUS)
        if APP.exists():
            os.rename(APP, PREVIOUS)
        os.rename(staging, APP)
        return changed
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise


def sandboxed(user, home, *command, timeout=300, extra=()):
    """Run a command as a service account with the units' main restrictions."""
    return run("systemd-run", "--wait", "--pipe", "--collect", "--quiet",
               "-p", f"User={user}", "-p", f"Group={user}",
               "-p", f"Environment=HOME={home}", "-p", "Environment=PYTHONDONTWRITEBYTECODE=1",
               "-p", "NoNewPrivileges=yes", "-p", "ProtectSystem=strict", "-p", "ProtectHome=yes",
               "-p", f"ReadWritePaths={home}", *extra, *command, check=False, timeout=timeout)


